def main() -> int:
    failures = 0
    tmp = Path(tempfile.mkdtemp(prefix="check-backlog-test-"))
    for i, (name, todo, progress, want_code, want_text, extra) in enumerate(CASES):
        d = tmp / f"case-{i}"
        d.mkdir(parents=True, exist_ok=True)
        (d / "TODO.md").write_text(todo)
        (d / "PROGRESS.md").write_text(progress)
        proc = subprocess.run(
            [sys.executable, "-B", str(CHECKER), "--todo", str(d / "TODO.md"), "--progress", str(d / "PROGRESS.md"), *extra],
            capture_output=True,
            text=True,
        )
        out = proc.stdout + proc.stderr
        ok = proc.returncode == want_code and want_text.lower() in out.lower()
        failures += 0 if ok else 1
        print(f"{'PASS' if ok else 'FAIL'}  {name}  (exit {proc.returncode}, wanted {want_code})")
        if not ok:
            print("      wanted substring: " + want_text)
            print("      output: " + out.strip().replace("\n", "\n      "))
    print(f"\n{len(CASES) - failures}/{len(CASES)} cases pass")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
